package com.realmeasure.app.export

import com.realmeasure.app.model.Pt
import java.util.Locale

/**
 * Pure SVG serialisation for true-scale CAD/laser export.
 *
 * The generated document uses millimetre units in both the `width`/`height`
 * attributes and the `viewBox`, so a 120 mm bracket imports as exactly
 * 120 mm in Fusion 360, Onshape, Inkscape or a laser cutter.
 */
object SvgBuilder {

    data class SvgDocument(
        val text: String,
        val widthMm: Double,
        val heightMm: Double,
    )

    /**
     * @param outerMm outer contour in canvas millimetres.
     * @param holesMm hole contours in canvas millimetres.
     * @param title document title (also used as the CAD object name).
     */
    fun build(
        outerMm: List<Pt>,
        holesMm: List<List<Pt>>,
        title: String = "RealMeasure 1:1 export",
    ): SvgDocument {
        require(outerMm.size >= 3) { "Outer contour needs at least 3 points" }

        val allPoints = outerMm + holesMm.flatten()
        val minX = allPoints.minOf { it.x }
        val minY = allPoints.minOf { it.y }
        val maxX = allPoints.maxOf { it.x }
        val maxY = allPoints.maxOf { it.y }
        val width = (maxX - minX).coerceAtLeast(0.001)
        val height = (maxY - minY).coerceAtLeast(0.001)

        val path = buildString {
            appendSubPath(outerMm, minX, minY)
            holesMm.forEach { hole ->
                if (hole.size >= 3) appendSubPath(hole, minX, minY)
            }
        }

        val text = buildString {
            appendLine("<?xml version=\"1.0\" encoding=\"UTF-8\"?>")
            appendLine(
                "<svg xmlns=\"http://www.w3.org/2000/svg\" version=\"1.1\" " +
                    "width=\"${number(width)}mm\" height=\"${number(height)}mm\" " +
                    "viewBox=\"0 0 ${number(width)} ${number(height)}\">",
            )
            appendLine("  <title>${escapeXml(title)}</title>")
            appendLine("  <desc>True-scale 1:1 contour generated by RealMeasure. Units are millimetres.</desc>")
            appendLine(
                "  <path d=\"$path\" fill-rule=\"evenodd\" fill=\"none\" " +
                    "stroke=\"#000000\" stroke-width=\"0.1\" stroke-linejoin=\"round\"/>",
            )
            appendLine("</svg>")
        }
        return SvgDocument(text = text, widthMm = width, heightMm = height)
    }

    private fun StringBuilder.appendSubPath(points: List<Pt>, minX: Double, minY: Double) {
        points.forEachIndexed { index, point ->
            val x = number(point.x - minX)
            val y = number(point.y - minY)
            if (index == 0) append("M $x $y ") else append("L $x $y ")
        }
        append("Z ")
    }

    private fun number(value: Double): String =
        String.format(Locale.US, "%.3f", value)
            .trimEnd('0')
            .trimEnd('.')
            .ifEmpty { "0" }

    private fun escapeXml(value: String): String = value
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace("\"", "&quot;")
}
